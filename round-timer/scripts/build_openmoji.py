"""Writes ../art/openmoji.js, the OpenMoji animals.

The pictures are the plain monkey plus the ones the kids approved on a test
sheet (timer-clipart-plan in github.com/kcarnold/research). Each becomes one
self-contained SVG string, so the timer draws them with no network access.

Usage:
    fetch https://registry.npmjs.org/@iconify-json/openmoji/-/openmoji-1.2.29.tgz
    and unpack it into an empty SETS_DIR/openmoji, then
    python3 -I build_openmoji.py SETS_DIR ../art/openmoji.js

1.2.29 is the version that reproduces the checked-in file exactly; later ones
redraw some outlines.
"""
import json, sys

sets_dir, out_path = sys.argv[1], sys.argv[2]
data = json.load(open(f"{sets_dir}/openmoji/package/icons.json"))
icons = data["icons"]
k = 32 / data.get("width", 72)  # placements are in a 32-unit box; OpenMoji is 72

def g(name, x, y, s):
    return f'<g transform="translate({x} {y}) scale({s * k:.4f})">{icons[name]["body"]}</g>'

# Placements copied from the research repo's combo_sheet.py, the version the kids saw.
HAT, GLASSES, HOLDING, IN = (4, 8, .75, 9, -1.5, .45), (2, 2, .875, 7, 6.5, .55), \
                            (1, 4, .75, 17, 14, .45), (9, 5, .5, 3, 10, .8)

# (timer name, animal icon, thing icon or None, placement)
# Names are short because they appear on a 62px tile and in
# "Start timer with <name>". Dropped: T-rex + balloon (OpenMoji's T-rex has no eye).
PICTURES = [
    ("Monkey",             "monkey-face", None,             (2, 2, .875)),
    ("Cool Monkey",        "monkey-face", "sunglasses",     GLASSES),
    ("Doughnut Sloth",     "sloth",       "doughnut",       HOLDING),
    ("Birthday Hamster",   "hamster",     "birthday-cake",  HOLDING),
    ("Ice-cream Croc",     "crocodile",   "soft-ice-cream", HOLDING),
    ("Pizza Shark",        "shark",       "pizza",          HOLDING),
    ("Cocoa Owl",          "owl",         "hot-beverage",   HOLDING),
    ("Rock-star Elephant", "elephant",    "guitar",         HOLDING),
    ("Fancy Hamster",      "hamster",     "top-hat",        HAT),
    ("King Koala",         "koala",       "crown",          (2, 6, .9, 10, 3, .4)),
    ("Shady Rabbit",       "rabbit-face", "sunglasses",     (2, 2, .875, 7.5, 12.5, .53)),
    ("Bath-time Hedgehog", "hedgehog",    "bathtub",        (6, 2, .7, 3, 10, .8)),
]

entries = []
for name, animal, thing, p in PICTURES:
    body = g(animal, *p[:3]) + (g(thing, *p[3:]) if thing else "")
    # width/height so older Safari gives the image a size to draw at.
    svg = f'<svg xmlns="http://www.w3.org/2000/svg" width="320" height="320" viewBox="0 0 32 32">{body}</svg>'
    entries.append(f"  {{name:{json.dumps(name)}, svg:{json.dumps(svg)}}}")

out = ("/* Generated by scripts/build_openmoji.py; don't edit by hand. */\n"
       "/* Art: OpenMoji (openmoji.org), CC BY-SA 4.0. The combined pictures are adaptations, */\n"
       "/* so they are CC BY-SA 4.0 too. */\n"
       "RT.art.openmoji = [\n" + ",\n".join(entries) + "\n];\n")

open(out_path, "w").write(out)
print(f"{len(PICTURES)} pictures, {len(out) / 1000:.0f} KB")
